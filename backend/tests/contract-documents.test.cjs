const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs/promises');
const express = require('express');
const jwt = require('jsonwebtoken');
const { MAX_SIZE, validateDocument, metadataFor, publicMetadata, documentPath } = require('../src/services/contractDocuments');
const fixtures = new Set();
const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<<>>\nendobj\n%%EOF');
let updateFails = false;
const contract = { id: 1, title: 'Existing Contract', status: 'active', document_metadata: null, async update(fields) { if (updateFails) throw new Error('database unavailable'); Object.assign(this, fields); } };
const modelsPath = require.resolve('../src/models');
require.cache[modelsPath] = { id: modelsPath, filename: modelsPath, loaded: true, exports: { Contract: { async findByPk(id) { return Number(id) === 1 ? contract : null; } } } };
const dbPath = require.resolve('../src/models/db');
require.cache[dbPath] = { id: dbPath, filename: dbPath, loaded: true, exports: { sequelize: { async transaction(callback) { return callback({ LOCK: { UPDATE: 'UPDATE' } }); } } } };
const controller = require('../src/controllers/contractDocumentController');
const { authenticate, requireAdmin } = require('../src/middleware/auth');
const app = express();
app.get('/:id/document', authenticate, requireAdmin, controller.getDocument);
app.post('/:id/document', authenticate, requireAdmin, controller.uploadMiddleware, controller.uploadDocument);
app.get('/:id/document/download', authenticate, requireAdmin, controller.downloadDocument);
let server;
after(async () => { if (server) await new Promise(resolve => server.close(resolve)); for (const file of fixtures) await fs.unlink(file).catch(() => {}); });

test('file validation rejects disguised files, oversized uploads and unsafe storage paths', () => {
  assert.throws(() => validateDocument({ originalname: 'test.pdf', mimetype: 'application/pdf', buffer: Buffer.from('<script>alert(1)</script>') }), /Only PDF/);
  assert.throws(() => validateDocument({ originalname: 'test.png', mimetype: 'image/png', buffer: pdf }), /must match/);
  assert.throws(() => validateDocument({ originalname: 'test.pdf', mimetype: 'application/pdf', buffer: Buffer.alloc(MAX_SIZE + 1) }), /10 MB/);
  assert.throws(() => documentPath({ key: '../../.env' }), /unavailable/);
  const info = validateDocument({ originalname: '../../signed.pdf', mimetype: 'application/pdf', buffer: pdf });
  assert.equal(info.name, 'signed.pdf');
  assert.equal(publicMetadata(info).key, undefined);
  assert.equal(publicMetadata({ ...info, uploadedBy: 42 }).uploadedBy, undefined);
  assert.deepEqual(metadataFor({ document_metadata: JSON.stringify(info) }), info);
});

test('authenticated document lifecycle: empty state, real multipart upload, persistence, download, duplicates and failures', async () => {
  process.env.JWT_SECRET = 'contract-document-test-secret';
  server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  const url = `http://127.0.0.1:${server.address().port}`;
  const headers = { Authorization: `Bearer ${jwt.sign({ id: 1, role: 'admin' }, process.env.JWT_SECRET)}` };
  const form = (buffer = pdf, name = 'signed.pdf') => { const body = new FormData(); body.append('document', new Blob([buffer], { type: 'application/pdf' }), name); return body; };
  assert.equal((await fetch(`${url}/1/document`)).status, 401);
  const staffHeaders = { Authorization: `Bearer ${jwt.sign({ id: 2, role: 'cashier', userType: 'staff' }, process.env.JWT_SECRET)}` };
  assert.equal((await fetch(`${url}/1/document`, { headers: staffHeaders })).status, 403);
  assert.equal((await fetch(`${url}/999/document`, { headers })).status, 404);
  assert.deepEqual(await (await fetch(`${url}/1/document`, { headers })).json(), { document: null });
  assert.equal((await fetch(`${url}/1/document/download`, { headers })).status, 404);
  assert.equal((await fetch(`${url}/1/document`, { method: 'POST', headers, body: form(Buffer.from('not a pdf')) })).status, 400);
  assert.equal((await fetch(`${url}/1/document`, { method: 'POST', headers, body: form(Buffer.alloc(MAX_SIZE + 1)) })).status, 400);
  const created = await fetch(`${url}/1/document`, { method: 'POST', headers, body: form() });
  assert.equal(created.status, 201);
  const metadata = (await created.json()).document;
  fixtures.add(documentPath(contract.document_metadata));
  assert.equal(metadata.name, 'signed.pdf');
  assert.equal(metadata.key, undefined);
  assert.equal(contract.title, 'Existing Contract');
  assert.equal(contract.status, 'active');
  assert.deepEqual((await (await fetch(`${url}/1/document`, { headers })).json()).document, metadata);
  const download = await fetch(`${url}/1/document/download`, { headers });
  assert.equal(download.status, 200);
  assert.match(download.headers.get('content-disposition'), /attachment;.*signed.pdf/);
  assert.equal(download.headers.get('content-type'), 'application/pdf');
  assert.equal(download.headers.get('cache-control'), 'private, no-store');
  assert.equal(download.headers.get('x-content-type-options'), 'nosniff');
  assert.deepEqual(Buffer.from(await download.arrayBuffer()), pdf);
  assert.equal((await fetch(`${url}/1/document`, { method: 'POST', headers, body: form() })).status, 409);
  const savedPath = documentPath(contract.document_metadata);
  await fs.unlink(savedPath); fixtures.delete(savedPath);
  assert.equal((await fetch(`${url}/1/document/download`, { headers })).status, 404);
  contract.document_metadata = null;
  updateFails = true;
  const storageBefore = await fs.readdir(require('../src/services/contractDocuments').STORAGE);
  assert.equal((await fetch(`${url}/1/document`, { method: 'POST', headers, body: form() })).status, 500);
  assert.deepEqual(await fs.readdir(require('../src/services/contractDocuments').STORAGE), storageBefore, 'Failed database writes must not leave orphan files.');
  assert.equal(contract.document_metadata, null);
});
